//! Colour palettes (port of ColorService, "Rainbow" scheme).

use eframe::egui::Color32;

const fn c(r: u8, g: u8, b: u8) -> Color32 {
    Color32::from_rgb(r, g, b)
}

/// 8 base colours, then 8 bright, then 8 dark (indexed by depth & 7).
const BOX_LIGHT: [Color32; 24] = [
    c(0xFF, 0x7F, 0x7F), c(0xFF, 0xBF, 0x7F), c(0xFF, 0xFF, 0x00), c(0x7F, 0xFF, 0x7F),
    c(0x7F, 0xFF, 0xFF), c(0xBF, 0xBF, 0xFF), c(0xBF, 0xBF, 0xBF), c(0xFF, 0x7F, 0xFF),
    c(0xFF, 0xBF, 0xBF), c(0xFF, 0xDF, 0xBF), c(0xFF, 0xFF, 0xBF), c(0xBF, 0xFF, 0xBF),
    c(0xDF, 0xFF, 0xFF), c(0xDF, 0xDF, 0xFF), c(0xDF, 0xDF, 0xDF), c(0xFF, 0xBF, 0xFF),
    c(0xBF, 0x7F, 0x7F), c(0xBF, 0x9F, 0x5F), c(0xBF, 0xBF, 0x3F), c(0x7F, 0xBF, 0x7F),
    c(0x7F, 0xBF, 0xBF), c(0x9F, 0x9F, 0xFF), c(0x9F, 0x9F, 0x9F), c(0xBF, 0x7F, 0xBF),
];

const BOX_DARK: [Color32; 24] = [
    c(0x8F, 0x3F, 0x3F), c(0x90, 0x60, 0x32), c(0x8A, 0x82, 0x28), c(0x3F, 0x78, 0x3F),
    c(0x35, 0x78, 0x78), c(0x55, 0x55, 0x9A), c(0x62, 0x62, 0x62), c(0x82, 0x42, 0x82),
    c(0x75, 0x48, 0x48), c(0x78, 0x58, 0x3F), c(0x78, 0x72, 0x40), c(0x48, 0x70, 0x48),
    c(0x42, 0x70, 0x70), c(0x5A, 0x5A, 0x85), c(0x50, 0x50, 0x50), c(0x70, 0x48, 0x70),
    c(0x55, 0x28, 0x28), c(0x55, 0x3A, 0x20), c(0x55, 0x50, 0x18), c(0x28, 0x50, 0x28),
    c(0x25, 0x50, 0x50), c(0x38, 0x38, 0x70), c(0x38, 0x38, 0x38), c(0x50, 0x28, 0x50),
];

#[derive(Clone, Copy)]
pub struct Palette {
    pub dark: bool,
    pub background: Color32,
    pub border: Color32,
    pub text: Color32,
    pub text_shadow: Color32,
    boxes: &'static [Color32; 24],
}

impl Palette {
    pub fn new(dark: bool) -> Self {
        if dark {
            Self {
                dark,
                background: c(0x16, 0x17, 0x18),
                border: c(0x30, 0x32, 0x32),
                text: c(0xD0, 0xD0, 0xC8),
                text_shadow: Color32::from_rgba_unmultiplied(0x20, 0x20, 0x20, 160),
                boxes: &BOX_DARK,
            }
        } else {
            Self {
                dark,
                background: c(0xEE, 0xEE, 0xEE),
                border: c(0xA0, 0xA0, 0xA0),
                text: Color32::BLACK,
                text_shadow: Color32::TRANSPARENT,
                boxes: &BOX_LIGHT,
            }
        }
    }

    /// (base, bright, dark) for a nesting depth.
    pub fn depth(&self, depth: i32) -> (Color32, Color32, Color32) {
        let i = (depth & 7) as usize;
        (self.boxes[i], self.boxes[i + 8], self.boxes[i + 16])
    }
}
